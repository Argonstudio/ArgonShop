/**
 * ArgonShop — feedback form handling (Contact Form 7).
 *
 * @package ArgonShop
 * @author  Ivan Voitkov
 *
 * ============================================================
 * PURPOSE
 * ============================================================
 *
 * Makes the feedback form embedded in the Fancybox modal
 * window work:
 *
 *   1. Disables Fancybox and turns the "Feedback" button
 *      into a regular link if the browser does not
 *      support FormData (for example, old IE) — then the form
 *      is submitted the traditional way on the /kontakty/ page.
 *
 *   2. Closes the modal window after the form is successfully sent,
 *      via the wpcf7mailsent event generated by CF7.
 *
 *   3. Shows a success message if the user submitted
 *      the form without directly clicking the button (for example, with a
 *      programmatic event). This protects against the modal window "sticking"
 *      in rare scenarios.
 *
 * ============================================================
 * EXTERNAL DEPENDENCIES
 * ============================================================
 *
 * - Contact Form 7 — generates the wpcf7mailsent event
 *   on the form container with an id like wpcf7-f{ID}-o{number}.
 *
 * - Fancybox 3 (jQuery-based) — used to show the modal
 *   window. The close event is called via the global object
 *   window.jQuery.fancybox.close().
 *
 * ============================================================
 * DOM ELEMENTS
 * ============================================================
 *
 * #linkFeedback         — the "Feedback" link in the header.
 * #wpcf7-f7-o1          — CF7 form container (the ID depends on
 *                         the plugin settings).
 * .wpcf7-submit         — form submit button.
 * .wpcf7-response-output — CF7 response block.
 *
 * ============================================================
 * USAGE
 * ============================================================
 *
 *     import { arsContactForm } from './modules/contact-form.js';
 *     arsContactForm.init();
 *
 * The module is safe to call on any page: if there is no feedback
 * form, nothing happens.
 */

'use strict';

import { qs, qsa, on } from '../../shared/dom.js';
import { t } from '../core/config.js';

/**
 * Delay before closing the modal window, in milliseconds.
 * Gives the user time to see the sent message.
 *
 * @type {number}
 */
const CLOSE_DELAY_MS = 1500;

/**
 * Feedback form module.
 */
class ArsContactForm {

    /** @type {boolean} */
    #initialized = false;

    /**
     * Initialization. Safe to call repeatedly.
     *
     * @return {void}
     */
    init() {

        if ( this.#initialized ) {
            return;
        }

        this.#initialized = true;

        this.#fallbackForOldBrowsers();
        this.#bindCf7Success();
        this.#bindSubmitClick();
    }

    // ============================================================
    // LINK WITHOUT FANCYBOX FOR OLD BROWSERS
    // ============================================================

    /**
     * If the browser does not support FormData, removes the Fancybox
     * attributes from the "Feedback" link and leads to the contacts
     * page.
     *
     * @return {void}
     */
    #fallbackForOldBrowsers() {

        if ( typeof window.FormData === 'function' ) {
            return;
        }

        const link = qs( '#linkFeedback' );

        if ( ! link ) {
            return;
        }

        link.setAttribute( 'href', '/kontakty/' );
        link.removeAttribute( 'data-fancybox' );
        link.removeAttribute( 'data-src' );
    }

    // ============================================================
    // SUCCESSFUL CF7 SUBMISSION
    // ============================================================

    /**
     * Subscribes to the wpcf7mailsent event and closes the modal
     * window after the form is successfully sent.
     *
     * @return {void}
     */
    #bindCf7Success() {

        const cf7Container = qs( '[id^="wpcf7-f"]' );

        if ( ! cf7Container ) {
            return;
        }

        cf7Container.addEventListener( 'wpcf7mailsent', () => {
            this.#closeFancyboxWithDelay();
        }, false );
    }

    // ============================================================
    // SUBMIT BUTTON CLICK HANDLING
    // ============================================================

    /**
     * Handles a click on the form submit button.
     *
     * If the click was outside the active area of the button
     * (a programmatic click or an event without coordinates) — stops
     * the submission and shows a success message.
     *
     * @return {void}
     */
    #bindSubmitClick() {

        const buttons = qsa( '.wpcf7-submit' );

        if ( ! buttons.length ) {
            return;
        }

        buttons.forEach( button => {

            on( button, 'click', ( event ) => {

                const rect = button.getBoundingClientRect();

                const relativeX = event.clientX - rect.left;
                const relativeY = event.clientY - rect.top;

                // A real mouse click — coordinates inside the button
                if ( relativeX > 0 && relativeY > 0 ) {
                    return;
                }

                // A programmatic or non-standard click
                event.preventDefault();

                const responseBlock = qs( '.wpcf7-response-output' );

                if ( responseBlock ) {
                    responseBlock.classList.add( 'wpcf7-mail-sent-ok' );
                    responseBlock.style.display = 'block';
                    responseBlock.textContent = t( 'messageSent' );
                }

                this.#closeFancyboxWithDelay();
            });
        });
    }

    // ============================================================
    // CLOSING THE MODAL WINDOW
    // ============================================================

    /**
     * Closes the current Fancybox modal window after the given
     * delay.
     *
     * Fancybox is loaded via jQuery, so it is called via
     * the global window.jQuery. If the object is unavailable
     * for some reason — just do nothing.
     *
     * @return {void}
     */
    #closeFancyboxWithDelay() {

        window.setTimeout( () => {

            if ( window.jQuery && window.jQuery.fancybox ) {
                window.jQuery.fancybox.close();
            }
        }, CLOSE_DELAY_MS );
    }
}

/**
 * Ready singleton of the feedback form module.
 *
 * @type {ArsContactForm}
 */
export const arsContactForm = new ArsContactForm();